type TranslationKey = keyof typeof english;

function activeDictionary(): typeof english {
  return vscode.env.language.toLowerCase().startsWith("zh") ? chinese : english;
}

export function t(key: TranslationKey, ...values: Array<string | number>): string {
  return values.reduce<string>(
    (message, value, index) => message.replace(`{${index}}`, String(value)),
    activeDictionary()[key]
  );
}
